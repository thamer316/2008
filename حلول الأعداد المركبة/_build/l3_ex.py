def circ(n, a, b, r, r2, given, q=None, rtex=None):
    f = circle_fig(f"e{n}.svg", a, b, r, center_lab=None)
    sx, sy = shift("x", a), shift("y", b)
    final = rf"إذن: دائرة مركزها $({num(a)},\,{num(b)})$ ونصف قطرها ${rtex or num(r)}$ ، ومعادلتها: $({sx})^2+({sy})^2={r2}$".replace("(x)^2", "x^2").replace("(y)^2", "y^2")
    return (n, q or given, circle_steps(a, b, r, r2, given, rtex=rtex) + [F(final), FIG(f)])


def bis(n, p, q_, given, eq, q=None, extra_rows=()):
    f = bisector_fig(f"e{n}.svg", p, q_)
    return (n, q or given, list(extra_rows) + bisector_steps(p, q_, given) + [F(rf"إذن: المحل الهندسي هو المُنصِّف العمودي، ومعادلته الديكارتية: ${eq}$"), FIG(f)])


def ray(n, a, b, th, th_tex, th_lab, given):
    f = ray_fig(f"e{n}.svg", a, b, th, th_lab)
    return (n, given, ray_steps(a, b, th_tex, given) + [F(rf"إذن: المحل الهندسي شعاع يبدأ بالنقطة $({num(a)},\,{num(b)})$ (دائرة مُفرَّغة)، كما في الشكل"), FIG(f)])


